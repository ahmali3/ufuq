// Generates reference fixtures for Ufuq's unit tests.
// Prayer times: praytimes.org algorithm (npm "praytimes"), UTC float hours.
// Qibla: adhan-js (independent implementation).
const PT = require('praytimes');
const adhan = require('adhan');

const cities = [
  ['Surrey', 49.1913, -122.849],
  ['Makkah', 21.4225, 39.8262],
  ['Karbala', 32.616, 44.0249],
  ['Qum', 34.6401, 50.8764],
  ['London', 51.5074, -0.1278],
  ['Jakarta', -6.2088, 106.8456],
  ['Istanbul', 41.0082, 28.9784],
  ['Toronto', 43.6532, -79.3832],
  ['Tromso', 69.6492, 18.9553]
];
const dates = [[2026, 3, 20], [2026, 6, 21], [2026, 9, 22], [2026, 12, 21], [2026, 10, 19]];
const methods = ['MWL', 'ISNA', 'Egypt', 'Makkah', 'Karachi', 'Tehran', 'Jafari'];
const keys = ['fajr', 'sunrise', 'dhuhr', 'asr', 'sunset', 'maghrib', 'isha', 'midnight'];

const pt = new PT();
const rows = [];
for (const m of methods) {
  for (const asr of ['Standard', 'Hanafi']) {
    if (asr === 'Hanafi' && m !== 'Karachi') continue;
    for (const [name, lat, lon] of cities) {
      for (const d of dates) {
        pt.setMethod(m);
        pt.adjust({ asr, highLats: 'AngleBased', dhuhr: '0 min' });
        const t = pt.getTimes(d, [lat, lon, 0], 0, 0, 'Float');
        const mins = keys.map(k => (typeof t[k] === 'number' && !isNaN(t[k])) ? Math.round(t[k] * 60 * 100) / 100 : 'NaN');
        rows.push(`    Ref("${m}", "${asr}", "${name}", ${lat}, ${lon}, ${d[0]}, ${d[1]}, ${d[2]}, doubleArrayOf(${mins.map(x => x === 'NaN' ? 'Double.NaN' : x.toFixed(2)).join(', ')}))`);
      }
    }
  }
}

const qibla = cities.map(([name, lat, lon]) =>
  `    QiblaRef("${name}", ${lat}, ${lon}, ${adhan.Qibla(new adhan.Coordinates(lat, lon)).toFixed(4)})`);

const out = `package com.ahmali.ufuq.core

// GENERATED by tools/reference/gen.js — do not edit by hand.
// Prayer times: praytimes.org algorithm (npm praytimes 0.0.5), highLats=AngleBased,
// dhuhr offset 0, elevation 0. Values are minutes after 00:00 UTC on the given date.
// Order: fajr, sunrise, dhuhr, asr, sunset, maghrib, isha, midnight. NaN = undefined.
// Qibla: adhan-js 4.4.6.

data class Ref(
    val method: String, val asr: String, val city: String,
    val lat: Double, val lon: Double, val y: Int, val m: Int, val d: Int,
    val minutesUtc: DoubleArray
)

data class QiblaRef(val city: String, val lat: Double, val lon: Double, val bearing: Double)

object ReferenceData {
  val times = listOf(
${rows.join(',\n')}
  )

  val qibla = listOf(
${qibla.join(',\n')}
  )
}
`;
process.stdout.write(out);
